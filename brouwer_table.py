def bounds(n, d):
    """Best known (lower, upper) for A(n, d), or None if outside the table."""
    if n < 1 or d < 1:
        return None
    if d > n:
        return (1, 1)
    if d == 1:
        return (1 << n, 1 << n)
    if d == 2:
        return (1 << (n - 1), 1 << (n - 1))
    if 2 * n < 3 * d:                 # n < 3d/2
        return (2, 2)
    if d % 2 == 1:                    # A(n, 2e-1) = A(n+1, 2e)
        return bounds(n + 1, d + 1)
    return n_d.get((n, d))


def exact(n, d):
    """The value if it is known exactly, else None."""
    b = bounds(n, d)
    return b[0] if b is not None and b[0] == b[1] else None
